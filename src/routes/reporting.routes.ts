import { Router } from 'express';
import { requirePermission } from '../middlewares/security';
import * as controller from '../controllers/reporting.controller';
export const reportingRouter = Router({ mergeParams: true });
reportingRouter.get('/analytics', requirePermission('analytics:read'), controller.getAnalytics);
reportingRouter.get('/audit-events', requirePermission('audit:read'), controller.listAuditEvents);
reportingRouter.get('/notifications', requirePermission('organization:read'), controller.listNotifications);
reportingRouter.patch('/notifications/:notificationId/read', requirePermission('organization:read'), controller.markNotification);
reportingRouter.get('/content/:contentId/export', requirePermission('export:read'), controller.exportContent);
reportingRouter.get('/evaluations', requirePermission('analytics:read'), controller.listEvaluations);
reportingRouter.post('/evaluations', requirePermission('evaluation:write'), controller.createEvaluation);
